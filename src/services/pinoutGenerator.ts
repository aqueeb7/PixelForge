/**
 * Automated C++ Firmware Pinout Header Generator (Spec 008)
 * Transforms the visual wiring netlist into reproducible C++ header code.
 */

import type { BoardProfile } from '../types/hardware'
import { getComponentDefinition } from '../core/hardware/ComponentDefinition'
import type { PlottedComponent, WireNet } from '../core/hardware/Netlist'

export interface PinoutGeneratorOptions {
  projectName?: string
  i2cSpeedHz?: number
}

export function generatePinoutHeader(
  board: BoardProfile,
  components: PlottedComponent[],
  nets: WireNet[],
  options: PinoutGeneratorOptions = {}
): string {
  const projectName = options.projectName || 'PixelForge Embedded Project'
  const i2cSpeed = options.i2cSpeedHz || 400000

  const allBoardPins = [...board.left_header, ...board.right_header]

  // Helper to extract GPIO number from a net connected to a component's pin
  const getGpioForPin = (instanceId: string, pinId: string): number | null => {
    const net = nets.find((n) =>
      n.nodes.some((node) => node.instanceId === instanceId && node.pinId === pinId)
    )
    if (!net) return null

    const boardNode = net.nodes.find((node) => node.instanceId === 'esp32')
    if (!boardNode) return null

    // Find pin in board profile
    const targetGpioMatch = boardNode.pinId.match(/(?:GPIO|P|D)(\d+)/i)
    const targetGpio = targetGpioMatch ? parseInt(targetGpioMatch[1], 10) : null

    const bPin = allBoardPins.find((p) => {
      if (p.label === boardNode.pinId) return true
      if (p.label.startsWith(boardNode.pinId + ' ') || p.label.startsWith(boardNode.pinId + '(')) return true
      if (targetGpio !== null && p.gpio === targetGpio) return true
      return false
    })

    if (bPin && bPin.gpio !== null) {
      return bPin.gpio
    }

    if (targetGpio !== null) return targetGpio

    return null
  }

  const lines: string[] = []
  lines.push('// =====================================================================')
  lines.push('// Auto-generated by PixelForge Hardware Studio — Do NOT Edit Manually')
  lines.push(`// Project: ${projectName}`)
  lines.push(`// Target MCU: ${board.name} (${board.chip_family})`)
  lines.push(`// Generated: ${new Date().toISOString()}`)
  lines.push('// =====================================================================')
  lines.push('#pragma once')
  lines.push('')
  lines.push('#include <Arduino.h>')
  lines.push('#include <Wire.h>')
  lines.push('')

  const defines: string[] = []
  const initStatements: string[] = []
  let hasI2c = false
  let oledSdaGpio: number | null = null
  let oledSclGpio: number | null = null

  // Process Components
  components.forEach((comp, idx) => {
    const def = getComponentDefinition(comp.definitionId)
    if (!def) return

    lines.push(`// --- ${comp.name} (${def.category}) ---`)

    if (def.category === 'Display') {
      const sda = getGpioForPin(comp.instanceId, 'SDA')
      const scl = getGpioForPin(comp.instanceId, 'SCL')
      const addr = comp.i2cAddress || def.i2cAddress || 0x3c
      const is32 = def.id.includes('128x32') || def.id.includes('091')

      if (sda !== null) {
        defines.push(`#define PIN_OLED_SDA ${sda}`)
        oledSdaGpio = sda
      }
      if (scl !== null) {
        defines.push(`#define PIN_OLED_SCL ${scl}`)
        oledSclGpio = scl
      }

      defines.push(`#define OLED_I2C_ADDRESS 0x${addr.toString(16).toUpperCase()}`)
      defines.push(`#define OLED_SCREEN_WIDTH 128`)
      defines.push(`#define OLED_SCREEN_HEIGHT ${is32 ? 32 : 64}`)
      hasI2c = true
    } else if (def.id === 'rotary-encoder-ec11') {
      const clk = getGpioForPin(comp.instanceId, 'CLK')
      const dt = getGpioForPin(comp.instanceId, 'DT')
      const sw = getGpioForPin(comp.instanceId, 'SW')

      if (clk !== null) {
        defines.push(`#define PIN_ENCODER_CLK ${clk}`)
        initStatements.push(`    pinMode(PIN_ENCODER_CLK, INPUT_PULLUP);`)
      }
      if (dt !== null) {
        defines.push(`#define PIN_ENCODER_DT ${dt}`)
        initStatements.push(`    pinMode(PIN_ENCODER_DT, INPUT_PULLUP);`)
      }
      if (sw !== null) {
        defines.push(`#define PIN_ENCODER_SW ${sw}`)
        initStatements.push(`    pinMode(PIN_ENCODER_SW, INPUT_PULLUP);`)
      }
    } else if (def.id === 'button-momentary') {
      const sig = getGpioForPin(comp.instanceId, 'PIN_A')
      if (sig !== null) {
        const macro = `PIN_BUTTON_${idx + 1}`
        defines.push(`#define ${macro} ${sig}`)
        initStatements.push(`    pinMode(${macro}, INPUT_PULLUP);`)
      }
    } else if (def.id === 'neopixel-ring-8') {
      const din = getGpioForPin(comp.instanceId, 'DIN')
      if (din !== null) {
        defines.push(`#define PIN_NEOPIXEL_DATA ${din}`)
        defines.push(`#define NEOPIXEL_NUM_LEDS 8`)
        initStatements.push(`    pinMode(PIN_NEOPIXEL_DATA, OUTPUT);`)
      }
    } else if (def.id === 'potentiometer-10k') {
      const sig = getGpioForPin(comp.instanceId, 'OUT')
      if (sig !== null) {
        defines.push(`#define PIN_POTENTIOMETER ${sig}`)
        initStatements.push(`    pinMode(PIN_POTENTIOMETER, INPUT);`)
      }
    } else if (def.id === 'microsd-spi') {
      const cs = getGpioForPin(comp.instanceId, 'CS')
      const sck = getGpioForPin(comp.instanceId, 'SCK')
      const mosi = getGpioForPin(comp.instanceId, 'MOSI')
      const miso = getGpioForPin(comp.instanceId, 'MISO')

      if (cs !== null) defines.push(`#define PIN_SD_CS ${cs}`)
      if (sck !== null) defines.push(`#define PIN_SD_SCK ${sck}`)
      if (mosi !== null) defines.push(`#define PIN_SD_MOSI ${mosi}`)
      if (miso !== null) defines.push(`#define PIN_SD_MISO ${miso}`)
      if (cs !== null) initStatements.push(`    pinMode(PIN_SD_CS, OUTPUT);`)
    }
  })

  lines.push('// --- PIN DEFINITIONS ---')
  if (defines.length > 0) {
    lines.push(...defines)
  } else {
    lines.push('// (No active peripheral signals wired to GPIO pins yet)')
  }
  lines.push('')

  // Init Hardware Function
  lines.push('/**')
  lines.push(' * Initialize hardware bus protocols and pin pull-ups')
  lines.push(' * Call this once in setup()')
  lines.push(' */')
  lines.push('inline void initHardwarePins() {')

  if (hasI2c && oledSdaGpio !== null && oledSclGpio !== null) {
    lines.push(`    // Initialize Hardware I2C Wire Bus (${i2cSpeed / 1000} kHz)`)
    lines.push(`    Wire.begin(PIN_OLED_SDA, PIN_OLED_SCL, ${i2cSpeed});`)
    lines.push('')
  }

  if (initStatements.length > 0) {
    lines.push('    // Configure GPIO Pin Modes')
    lines.push(...initStatements)
  } else if (!hasI2c) {
    lines.push('    // No pin configurations needed')
  }

  lines.push('}')
  lines.push('')

  return lines.join('\n')
}
